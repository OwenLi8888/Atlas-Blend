import { afterEach, expect, it } from 'vitest';
import express from 'express';
import sharp from 'sharp';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { resizedImages } from './images';
import { testCatalog } from './testing';
const cleanups: (() => Promise<unknown>)[] = [];
afterEach(async () => { await Promise.all(cleanups.splice(0).map(fn => fn())); });
it('coalesces originals, resizes grids, and reuses disk variants', async () => {
 const dir = await mkdtemp(path.join(tmpdir(), 'gallery-images-'));
 cleanups.push(() => rm(dir, { recursive:true, force:true }));
 const original = await sharp({create:{width:1600,height:1000,channels:3,background:'red'}}).jpeg().toBuffer();
 let fetches=0;
 const catalog=testCatalog([{id:'one',vector:[1,0]}]);
 const app=express();
 app.get('/api/image',resizedImages(catalog,async()=>{fetches++; return new Response(new Uint8Array(original),{headers:{'content-type':'image/jpeg'}});},dir));
 const server=app.listen(0,'127.0.0.1');
 cleanups.push(()=>new Promise<void>(resolve=>server.close(()=>resolve())));
 await new Promise<void>(resolve=>server.once('listening',resolve));
 const address=server.address(); if(!address||typeof address==='string') throw Error('port');
 const url=`http://127.0.0.1:${address.port}/api/image?id=one&width=480`;
 const responses=await Promise.all([fetch(url),fetch(url)]);
 const bytes=Buffer.from(await responses[0].arrayBuffer());
 expect((await sharp(bytes).metadata()).width).toBe(480);
 expect((await sharp(bytes).metadata()).height).toBe(300);
 expect(fetches).toBe(1);
 expect((await fetch(url)).status).toBe(200);
 expect(fetches).toBe(1);
 expect((await fetch(url.replace('480','999'))).status).toBe(400);
});
